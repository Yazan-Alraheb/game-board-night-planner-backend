-- Issue #10 only. Run with psql -X -v ON_ERROR_STOP=1 -f <this-file>.
-- Target schema is explicitly public. No connection settings are embedded.
BEGIN;
SET LOCAL lock_timeout = '5s';
SET LOCAL statement_timeout = '5min';
SET LOCAL search_path = pg_catalog, public;
-- Prevent membership/data changes and referenced-row deletion during validation.
LOCK TABLE public.users, public.game_nights IN SHARE ROW EXCLUSIVE MODE;
LOCK TABLE public.conversations, public.conversation_members, public.messages
    IN ACCESS EXCLUSIVE MODE;

-- Temporary reference tables let PostgreSQL parse the expected checks/indexes.
CREATE TEMP TABLE expected_conversations (
    id integer PRIMARY KEY, type varchar NOT NULL, game_night_id integer UNIQUE,
    created_at timestamptz NOT NULL,
    CONSTRAINT ck_conversation_type CHECK (type IN ('private', 'group')),
    CONSTRAINT ck_private_conversation_no_game_night
        CHECK (type != 'private' OR game_night_id IS NULL)
) ON COMMIT DROP;
CREATE INDEX expected_conversations_id ON expected_conversations (id);
CREATE TEMP TABLE expected_conversation_members (
    conversation_id integer, user_id integer, PRIMARY KEY (conversation_id, user_id)
) ON COMMIT DROP;
CREATE TEMP TABLE expected_messages (
    id integer PRIMARY KEY, conversation_id integer NOT NULL, user_id integer NOT NULL,
    content text NOT NULL, created_at timestamptz NOT NULL,
    CONSTRAINT ck_message_content_not_empty CHECK (length(trim(content)) > 0)
) ON COMMIT DROP;
CREATE INDEX expected_messages_id ON expected_messages (id);

ALTER TABLE expected_conversations
    ADD COLUMN private_user_low_id integer,
    ADD COLUMN private_user_high_id integer,
    ADD CONSTRAINT uq_conversation_private_pair
        UNIQUE (private_user_low_id, private_user_high_id),
    ADD CONSTRAINT ck_conversation_private_pair CHECK (
        (type = 'private' AND private_user_low_id IS NOT NULL
         AND private_user_high_id IS NOT NULL AND private_user_low_id < private_user_high_id)
        OR (type = 'group' AND private_user_low_id IS NULL AND private_user_high_id IS NULL)
    );
ALTER TABLE expected_messages ADD CONSTRAINT ck_message_content_length CHECK (length(content) <= 2000);
CREATE INDEX expected_members_user_conversation ON expected_conversation_members (user_id, conversation_id);
CREATE INDEX expected_messages_conversation_created_id
    ON expected_messages (conversation_id, created_at DESC, id DESC);

-- Fail closed on schema drift, including already-applied/partially-applied migration.
CREATE FUNCTION pg_temp.assert_chat_schema(upgraded boolean) RETURNS void
LANGUAGE plpgsql AS $check$
DECLARE
    t text;
    actual oid;
    expected oid;
    actual_signature jsonb;
    expected_signature jsonb;
    spec record;
    fk_count integer;
BEGIN
    FOREACH t IN ARRAY ARRAY['conversations', 'conversation_members', 'messages'] LOOP
        actual := to_regclass('public.' || t);
        expected := to_regclass('pg_temp.expected_' || t);
        IF actual IS NULL OR (SELECT relkind FROM pg_class WHERE oid = actual) != 'r' THEN
            RAISE EXCEPTION 'Expected ordinary public table: %', t;
        END IF;
        -- Compare columns by name (physical order may differ after ADD COLUMN).
        SELECT jsonb_agg(jsonb_build_array(attname, atttypid, atttypmod, attnotnull,
                                         attidentity, attgenerated) ORDER BY attname)
          INTO actual_signature FROM pg_attribute
          WHERE attrelid = actual AND attnum > 0 AND NOT attisdropped;
        SELECT jsonb_agg(jsonb_build_array(attname, atttypid, atttypmod, attnotnull,
                                         attidentity, attgenerated) ORDER BY attname)
          INTO expected_signature FROM pg_attribute
          WHERE attrelid = expected AND attnum > 0 AND NOT attisdropped;
        IF actual_signature IS DISTINCT FROM expected_signature THEN
            RAISE EXCEPTION 'Unexpected columns/types/nullability on %', t;
        END IF;
        IF EXISTS (SELECT FROM pg_attrdef d JOIN pg_attribute a
                   ON a.attrelid = d.adrelid AND a.attnum = d.adnum
                   WHERE d.adrelid = actual AND a.attname != 'id')
           OR (t != 'conversation_members' AND (
               pg_get_serial_sequence('public.' || t, 'id') IS NULL
               OR NOT EXISTS (SELECT FROM pg_attrdef d JOIN pg_attribute a
                   ON a.attrelid = d.adrelid AND a.attnum = d.adnum
                   WHERE d.adrelid = actual AND a.attname = 'id'
                     AND pg_get_expr(d.adbin, d.adrelid) LIKE 'nextval(%')
           )) THEN
            RAISE EXCEPTION 'Unexpected defaults/sequence on %', t;
        END IF;
        -- Names are deliberately ignored: autogenerated names vary by database.
        SELECT jsonb_agg(sig ORDER BY sig::text) INTO actual_signature FROM (
            SELECT jsonb_build_array(c.contype,
                ARRAY(SELECT a.attname FROM unnest(c.conkey) WITH ORDINALITY k(n, pos)
                      JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.pos),
                CASE WHEN c.contype = 'c' THEN pg_get_expr(c.conbin, c.conrelid) END,
                c.convalidated, c.condeferrable, c.condeferred) AS sig
            FROM pg_constraint c WHERE c.conrelid = actual AND c.contype != 'f'
        ) s;
        SELECT jsonb_agg(sig ORDER BY sig::text) INTO expected_signature FROM (
            SELECT jsonb_build_array(c.contype,
                ARRAY(SELECT a.attname FROM unnest(c.conkey) WITH ORDINALITY k(n, pos)
                      JOIN pg_attribute a ON a.attrelid = c.conrelid AND a.attnum = k.n ORDER BY k.pos),
                CASE WHEN c.contype = 'c' THEN pg_get_expr(c.conbin, c.conrelid) END,
                c.convalidated, c.condeferrable, c.condeferred) AS sig
            FROM pg_constraint c WHERE c.conrelid = expected
        ) s;
        IF actual_signature IS DISTINCT FROM expected_signature THEN
            RAISE EXCEPTION 'Unexpected or missing primary/unique/check constraints on %', t;
        END IF;
        -- Reject equivalent indexes under other names as well as unexpected indexes.
        SELECT jsonb_agg(sig ORDER BY sig::text) INTO actual_signature FROM (
            SELECT jsonb_build_array(am.amname, i.indisunique, i.indisprimary,
                i.indisvalid, i.indisready, i.indimmediate,
                to_jsonb(i)->>'indnullsnotdistinct', i.indnkeyatts, i.indnatts,
                ARRAY(SELECT pg_get_indexdef(i.indexrelid, n, true)
                      FROM generate_series(1, i.indnatts) n),
                pg_get_expr(i.indpred, i.indrelid)) AS sig
            FROM pg_index i JOIN pg_class x ON x.oid = i.indexrelid
            JOIN pg_am am ON am.oid = x.relam WHERE i.indrelid = actual
        ) s;
        SELECT jsonb_agg(sig ORDER BY sig::text) INTO expected_signature FROM (
            SELECT jsonb_build_array(am.amname, i.indisunique, i.indisprimary,
                i.indisvalid, i.indisready, i.indimmediate,
                to_jsonb(i)->>'indnullsnotdistinct', i.indnkeyatts, i.indnatts,
                ARRAY(SELECT pg_get_indexdef(i.indexrelid, n, true)
                      FROM generate_series(1, i.indnatts) n),
                pg_get_expr(i.indpred, i.indrelid)) AS sig
            FROM pg_index i JOIN pg_class x ON x.oid = i.indexrelid
            JOIN pg_am am ON am.oid = x.relam WHERE i.indrelid = expected
        ) s;
        IF actual_signature IS DISTINCT FROM expected_signature THEN
            RAISE EXCEPTION 'Unexpected, duplicate, or missing indexes on %', t;
        END IF;
        fk_count := 0;
        FOR spec IN SELECT * FROM (VALUES
            ('conversations', 'game_night_id', 'game_nights', 'id'),
            ('conversations', 'private_user_low_id', 'users', 'id'),
            ('conversations', 'private_user_high_id', 'users', 'id'),
            ('conversation_members', 'conversation_id', 'conversations', 'id'),
            ('conversation_members', 'user_id', 'users', 'id'),
            ('messages', 'conversation_id', 'conversations', 'id'),
            ('messages', 'user_id', 'users', 'id')
        ) v(tbl, col, ref_tbl, ref_col)
        WHERE tbl = t
          AND (upgraded OR col NOT IN ('private_user_low_id', 'private_user_high_id')) LOOP
            fk_count := fk_count + 1;
            IF (SELECT count(*) FROM pg_constraint c
                WHERE c.conrelid = actual AND c.contype = 'f'
                  AND c.conkey = ARRAY[(SELECT attnum FROM pg_attribute
                      WHERE attrelid = actual AND attname = spec.col)]::smallint[]
                  AND c.confrelid = to_regclass('public.' || spec.ref_tbl)
                  AND c.confkey = ARRAY[(SELECT attnum FROM pg_attribute
                      WHERE attrelid = c.confrelid AND attname = spec.ref_col)]::smallint[]
                  AND c.confdeltype = 'c' AND c.confupdtype = 'a'
                  AND c.confmatchtype = 's' AND c.convalidated
                  AND NOT c.condeferrable AND NOT c.condeferred) != 1 THEN
                RAISE EXCEPTION 'Unexpected or missing foreign key %.%', t, spec.col;
            END IF;
        END LOOP;
        IF (SELECT count(*) FROM pg_constraint WHERE conrelid = actual AND contype = 'f') != fk_count THEN
            RAISE EXCEPTION 'Unexpected foreign keys on %', t;
        END IF;
        IF EXISTS (SELECT FROM pg_trigger WHERE tgrelid = actual AND NOT tgisinternal)
           OR EXISTS (SELECT FROM pg_class WHERE oid = actual AND (relrowsecurity OR relforcerowsecurity)) THEN
            RAISE EXCEPTION 'Custom triggers or row security on % require manual review', t;
        END IF;
    END LOOP;
END;
$check$;
-- Only accept the exact Issue #10 schema and the marker written by its upgrade.
SELECT pg_temp.assert_chat_schema(true);
DO $rollback$
DECLARE marker jsonb; original_name text; original_comment text;
BEGIN
    SELECT obj_description(oid, 'pg_constraint')::jsonb INTO STRICT marker
      FROM pg_constraint WHERE conrelid = 'public.conversations'::regclass
      AND conname = 'uq_conversation_game_night';
    IF marker IS NULL OR marker->>'migration' IS DISTINCT FROM '010_chat_messaging'
       OR marker->>'original_name' IS NULL THEN
        RAISE EXCEPTION 'Missing migration 010 provenance; do not guess the original constraint name';
    END IF;
    original_name := marker->>'original_name';
    original_comment := marker->>'original_comment';
    ALTER TABLE public.conversations DROP CONSTRAINT uq_conversation_private_pair,
        DROP CONSTRAINT ck_conversation_private_pair,
        DROP CONSTRAINT conversations_private_user_low_id_fkey,
        DROP CONSTRAINT conversations_private_user_high_id_fkey,
        DROP COLUMN private_user_low_id, DROP COLUMN private_user_high_id;
    ALTER TABLE public.messages DROP CONSTRAINT ck_message_content_length;
    DROP INDEX public.ix_conversation_members_user_conversation;
    DROP INDEX public.ix_messages_conversation_created_id;
    IF original_name != 'uq_conversation_game_night' THEN
        EXECUTE format('ALTER TABLE public.conversations RENAME CONSTRAINT uq_conversation_game_night TO %I', original_name);
    END IF;
    EXECUTE format('COMMENT ON CONSTRAINT %I ON public.conversations IS %L', original_name, original_comment);
END;
$rollback$;
DROP INDEX pg_temp.expected_members_user_conversation;
DROP INDEX pg_temp.expected_messages_conversation_created_id;
ALTER TABLE expected_messages DROP CONSTRAINT ck_message_content_length;
ALTER TABLE expected_conversations DROP COLUMN private_user_low_id, DROP COLUMN private_user_high_id;
SELECT pg_temp.assert_chat_schema(false);
COMMIT;
